export async function loader(args: LoaderFunctionArgs) {
  // Start fetching non-critical data without blocking time to first byte
  const deferredData = loadDeferredData(args);

  // Await the critical data required to render initial state of the page
  const criticalData = await loadCriticalData(args);

  return defer({
    ...deferredData,
    ...criticalData,
  });
}

/**
 * Load data necessary for rendering content above the fold. This is the critical data
 * needed to render the page. If it's unavailable, the whole page should 400 or 500 error.
 */
async function loadCriticalData({request, context}: LoaderFunctionArgs) {
  const [layout] = await Promise.all([
    getLayoutData(context),
    // Add other queries here, so that they are loaded in parallel
  ]);

  const seo = seoPayload.root({shop: layout.shop, url: request.url});

  const {storefront, env} = context;

  return {
    layout,
    seo,
    shop: getShopAnalytics({
      storefront,
      publicStorefrontId: env.PUBLIC_STOREFRONT_ID,
    }),
    consent: {
      checkoutDomain: env.PUBLIC_CHECKOUT_DOMAIN,
      storefrontAccessToken: env.PUBLIC_STOREFRONT_API_TOKEN,
      withPrivacyBanner: true,
    },
    selectedLocale: storefront.i18n,
  };
}

/**
 * Load data for rendering content below the fold. This data is deferred and will be
 * fetched after the initial page load. If it's unavailable, the page should still 200.
 * Make sure to not throw any errors here, as it will cause the page to 500.
 */
function loadDeferredData({context}: LoaderFunctionArgs) {
  const {cart, customerAccount, env} = context;

  // Enrich cart lines with real inventory from São Lourenço (Admin API).
  // On any error the cart is returned unchanged — badges just won't show.
  const enrichedCart = (async () => {
    const cartData = await cart.get();
    const lines: any[] = cartData?.lines?.nodes ?? [];
    if (!lines.length) return cartData;
    const variantIds: string[] = lines
      .map((l: any) => l?.merchandise?.id)
      .filter(Boolean);
    const invMap = await getInventoryBySaoLourenco(env, variantIds);
    if (invMap.size) {
      lines.forEach((line: any) => {
        const qty = invMap.get(line?.merchandise?.id);
        if (qty !== undefined && line?.merchandise) {
          line.merchandise.quantityAvailable = qty;
        }
      });
    }
    return cartData;
  })();

  return {
    isLoggedIn: customerAccount.isLoggedIn(),
    cart: enrichedCart,
    discountTiers: getDiscountTiers(env),
  };
}

export const meta = ({data}: MetaArgs<typeof loader>) => {
  return getSeoMeta(data!.seo as SeoConfig);
};

function Layout({children}: {children?: React.ReactNode}) {
  const nonce = useNonce();
  const data = useRouteLoaderData<typeof loader>('root');
  const locale = data?.selectedLocale ?? DEFAULT_LOCALE;

  return (
    <html lang={locale.language}>
      <head>
        <meta charSet="utf-8" />
        <meta name="viewport" content="width=device-width,initial-scale=1" />
        <meta name="msvalidate.01" content="A352E6A0AF9A652267361BBB572B8468" />
        <link rel="stylesheet" href={styles}></link>
        <Meta />
        <Links />
      </head>
      <body>
        {data ? (
          <Analytics.Provider
            cart={data.cart}
            shop={data.shop}
            consent={data.consent}
          >
            <PageLayout
              key={`${locale.language}-${locale.country}`}
              layout={data.layout as any}
            >
              {children}
            </PageLayout>
          </Analytics.Provider>
        ) : (
          children
        )}
        <ScrollRestoration nonce={nonce} />
        <Scripts nonce={nonce} />
      </body>
    </html>
  );
}

export default function App() {
  return (
    <Layout>
      <Outlet />
    </Layout>
  );
}

export function ErrorBoundary({error}: {error: Error}) {
  const routeError = useRouteError();
  const isRouteError = isRouteErrorResponse(routeError);

  let title = 'Erro';
  let pageType = 'page';

  if (isRouteError) {
    title = 'Não encontrado';
    if (routeError.status === 404) pageType = routeError.data || pageType;
  }

  return (
    <Layout>
      {isRouteError ? (
        <>
          {routeError.status === 404 ? (
            <NotFound type={pageType} />
          ) : (
            <GenericError
              error={{message: `${routeError.status} ${routeError.data}`}}
            />
          )}
        </>
      ) : (
        <GenericError error={error instanceof Error ? error : undefined} />
      )}
    </Layout>
  );
}

export type AnnouncementBar = {
  message: string;
  link?: string;
  active: boolean;
  placement: 'global' | 'cart' | 'both';
  bgColor?: string;
  textColor?: string;
  sortOrder: number;
  /** For cart bars: show this bar only when totalQuantity >= minCartQuantity.
   *  The bar with the highest qualifying minCartQuantity wins. */
  minCartQuantity: number;
};

function parseAnnouncementBars(nodes: Array<{fields: Array<{key: string; value: string | null}>}>): AnnouncementBar[] {
  return nodes
    .map((node) => {
      const f = Object.fromEntries(node.fields.map((x) => [x.key, x.value ?? '']));
      return {
        message: f.message ?? '',
        link: f.link || undefined,
        active: f.active === 'true',
        placement: (f.placement || 'global') as AnnouncementBar['placement'],
        bgColor: f.bg_color || undefined,
        textColor: f.text_color || undefined,
        sortOrder: parseInt(f.sort_order || '0', 10),
        minCartQuantity: parseInt(f.min_cart_quantity || '0', 10),
      };
    })
    .filter((b) => b.active && b.message)
    .sort((a, b) => a.sortOrder - b.sortOrder);
}

const LAYOUT_QUERY = `#graphql
  query layout(
    $language: LanguageCode
    $headerMenuHandle: String!
    $footerMenuHandle: String!
  ) @inContext(language: $language) {
    shop {
      ...Shop
    }
    headerMenu: menu(handle: $headerMenuHandle) {
      ...Menu
    }
    footerMenu: menu(handle: $footerMenuHandle) {
      ...Menu
    }
    announcementBars: metaobjects(type: "announcement_bar", first: 20) {
      nodes {
        fields { key value }
      }
    }
  }
  fragment Shop on Shop {
    id
    name
    description
    primaryDomain {
      url
    }
    brand {
      logo {
        image {
          url
        }
      }
    }
  }
  fragment MenuItem on MenuItem {
    id
    resourceId
    tags
    title
    type
    url
  }
  fragment ChildMenuItem on MenuItem {
    ...MenuItem
  }
  fragment ParentMenuItem on MenuItem {
    ...MenuItem
    items {
      ...ChildMenuItem
    }
  }
  fragment Menu on Menu {
    id
    items {
      ...ParentMenuItem
    }
  }
` as const;

async function getLayoutData({storefront, env}: AppLoadContext) {
  const data = await storefront.query(LAYOUT_QUERY, {
    variables: {
      headerMenuHandle: 'main-menu',
      footerMenuHandle: 'footer',
      language: storefront.i18n.language,
    },
  });

  invariant(data, 'No data returned from Shopify API');

  /*
    Modify specific links/routes (optional)
    @see: https://shopify.dev/api/storefront/unstable/enums/MenuItemType
    e.g here we map:
      - /blogs/news -> /news
      - /blog/news/blog-post -> /news/blog-post
      - /collections/all -> /products
  */
  const customPrefixes = {BLOG: '', CATALOG: 'products'};

  const headerMenu = data?.headerMenu
    ? parseMenu(
        data.headerMenu,
        data.shop.primaryDomain.url,
        env,
        customPrefixes,
      )
    : undefined;

  const footerMenu = data?.footerMenu
    ? parseMenu(
        data.footerMenu,
        data.shop.primaryDomain.url,
        env,
        customPrefixes,
      )
    : undefined;

  const announcementBars = parseAnnouncementBars(
    (data as any)?.announcementBars?.nodes ?? [],
  );

  return {shop: data.shop, headerMenu, footerMenu, announcementBars};
}
